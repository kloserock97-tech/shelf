const DICT: Record<Lang, Record<Key, string>> = { en, ru };

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}) {
  return DICT[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

// Russian has three plural forms: 1 элемент, 2 элемента, 5 элементов.
export function plural(lang: Lang, n: number, forms: { en: [string, string]; ru: [string, string, string] }) {
  if (lang === 'en') return n === 1 ? forms.en[0] : forms.en[1];
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return forms.ru[0];
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms.ru[1];
  return forms.ru[2];
}
export const itemsWord = (lang: Lang, n: number) => plural(lang, n, { en: ['item', 'items'], ru: ['элемент', 'элемента', 'элементов'] });

export const formatDate = (lang: Lang, d: Date) =>
  lang === 'ru'
    ? d.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric' }).replace(/\s*г\.$/, '')
    : d.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
